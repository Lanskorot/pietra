    def handle(self, *args, **kwargs):
        with transaction.atomic():
            self.create_categories_and_attributes()

    def create_categories_and_attributes(self):
        lines = self.structure.strip().split('\n')
        # Удаляем пустые строки и строки с одними пробелами
        lines = [line for line in lines if line.strip() != '']
        
        # Определяем уровень отступа (количество пробелов в начале)
        # В структуре отступы заданы пробелами и табуляциями? Кажется, используются пробелы.
        # Будем считать количество пробелов до первого непробельного символа.
        # Также есть табуляции, но в тексте они видны как 8 пробелов, но лучше заменить табуляцию на пробелы.
        # Удалим все непечатные символы, оставим пробелы.
        # Для простоты будем считать, что уровень = количество пробелов // 4 (т.к. каждый уровень 4 пробела).
        # Но в вашем тексте отступы непостоянны, поэтому лучше считать по количеству ведущих пробелов.
        
        # Сначала приведём строки к единообразному виду: заменим табуляции на пробелы
        lines = [line.replace('\t', '    ') for line in lines]
        
        # Строим дерево узлов: каждый узел - dict с ключами: name, level, children, parent
        root = {'name': 'root', 'level': -1, 'children': [], 'parent': None}
        stack = [root]
        for line in lines:
            stripped = line.lstrip()
            if not stripped:
                continue
            # Определяем уровень: количество пробелов в начале
            leading_spaces = len(line) - len(stripped)
            # Нормализуем уровень: считаем, что один уровень = 4 пробела
            level = leading_spaces // 4
            # Если отступ не кратен 4, округлим вниз (может быть 1 пробел, но в структуре обычно кратно)
            # Или просто используем количество пробелов как уровень.
            # Поскольку у вас отступы не строгие, лучше использовать число пробелов как есть.
            # Но тогда нам нужно сравнивать уровни. Сделаем так: level = leading_spaces // 4
            # Это даст нам 0,1,2,... для уровней.
            # Если есть смешанные отступы, можно просто взять leading_spaces.
            # Для надёжности используем leading_spaces.
            level = leading_spaces  # но тогда уровни будут большими, проще делить на 4.
            # Попробуем делить на 4: в вашем тексте каждый уровень примерно 4 пробела.
            level = leading_spaces // 4 if leading_spaces % 4 == 0 else leading_spaces // 4
            # Но для безопасности используем деление на 4 с округлением вниз.
            level = leading_spaces // 4
            
            # Находим родителя для текущего уровня
            while stack and stack[-1]['level'] >= level:
                stack.pop()
            parent = stack[-1]
            
            # Создаём узел
            node = {
                'name': stripped,
                'level': level,
                'children': [],
                'parent': parent
            }
            parent['children'].append(node)
            stack.append(node)
        
        # Теперь обходим дерево и создаём категории и атрибуты.
        # Для каждого узла определяем, является ли он категорией или атрибутом.
        # Если у узла есть дети, и все его дети не имеют детей (т.е. листья), то узел - атрибут.
        # Иначе - категория.
        
        def is_attribute(node):
            if not node['children']:
                return False  # лист не является атрибутом (это значение)
            for child in node['children']:
                if child['children']:
                    return False  # есть дочерние категории, значит это категория
            return True  # все дети - листья, значит это атрибут
        
        # Рекурсивно создаём категории
        def create_categories(node, parent_category=None):
            # Если узел - категория (имеет детей, но не является атрибутом)
            if node['children'] and not is_attribute(node):
                # Это категория
                cat, created = Category.objects.get_or_create(
                    name=node['name'],
                    defaults={
                        'slug': slugify(node['name']),
                        'parent': parent_category,
                    }
                )
                if created:
                    self.stdout.write(f'Создана категория: {cat.name}')
                # Рекурсивно обрабатываем детей
                for child in node['children']:
                    create_categories(child, cat)
            else:
                # Это либо атрибут (имеет детей-листья), либо лист (значение)
                # Для атрибута создаём атрибут и привязываем к текущей категории
                if node['children'] and is_attribute(node):
                    # Создаём атрибут для родительской категории
                    if parent_category is None:
                        self.stdout.write(f'Ошибка: атрибут {node["name"]} без родительской категории')
                        return
                    # Создаём слаг на основе названия категории и атрибута
                    attr_slug = slugify(f"{parent_category.name}_{node['name']}")
                    # Проверяем существование атрибута с таким слагом (уникальность)
                    attr, created = Attribute.objects.get_or_create(
                        slug=attr_slug,
                        defaults={
                            'name': node['name'],
                            'type': 'select',
                            'options': [],
                            'is_filterable': True,
                            'is_required': False,
                        }
                    )
                    # Добавляем категорию в ManyToMany (связываем атрибут с этой категорией)
                    if parent_category not in attr.categories.all():
                        attr.categories.add(parent_category)
                    
                    if created:
                        self.stdout.write(f'Создан атрибут: {attr.name} для категории {parent_category.name}')
                    else:
                        self.stdout.write(f'Атрибут {attr.name} уже существует, обновляем опции')
                    
                    # Собираем значения (дети) и добавляем их в options
                    options = [child['name'].strip() for child in node['children']]
                    # Обновляем options, объединяя с существующими (чтобы не потерять ранее добавленные)
                    existing_options = set(attr.options)
                    new_options = set(options)
                    all_options = list(existing_options | new_options)
                    if set(attr.options) != all_options:
                        attr.options = all_options
                        attr.save(update_fields=['options'])
                        self.stdout.write(f'Обновлены опции для атрибута {attr.name}')
                else:
                    # Лист (значение) - ничего не делаем, оно уже обработано как опция атрибута
                    pass
        
        # Начинаем с корневого узла (root)
        for child in root['children']:
            create_categories(child, None)
        
        self.stdout.write(self.style.SUCCESS('Импорт структуры завершён'))